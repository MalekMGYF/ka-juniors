create or replace function touch_mafioso_room_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_touch_mafioso_room on mafioso_rooms;
create trigger trg_touch_mafioso_room
before update on mafioso_rooms
for each row execute function touch_mafioso_room_updated_at();

