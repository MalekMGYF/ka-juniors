create table if not exists mafioso_cases (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(trim(title)) between 3 and 90),
  subtitle text not null default '',
  briefing text not null default '',
  reveal_title text not null default 'الحقيقة الكاملة',
  reveal_story text not null default '',
  reveal_audio_path text,
  is_active boolean not null default true,
  created_by uuid references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists mafioso_case_roles (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references mafioso_cases(id) on delete cascade,
  role_name text not null check (char_length(trim(role_name)) between 2 and 60),
  public_motive text not null default '',
  private_card_text text not null default '',
  alignment text not null check (alignment in ('mafia', 'innocent')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(case_id, role_name)
);

create table if not exists mafioso_case_clues (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references mafioso_cases(id) on delete cascade,
  round_number integer not null check (round_number between 1 and 4),
  clue_text text not null check (char_length(trim(clue_text)) between 4 and 500),
  created_at timestamptz not null default now(),
  unique(case_id, round_number)
);

create table if not exists mafioso_rooms (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (char_length(code) between 4 and 10),
  name text not null default 'غرفة القضية',
  case_id uuid references mafioso_cases(id) on delete set null,
  status text not null default 'waiting' check (status in ('waiting', 'role_reveal', 'boss_intro', 'clue_reveal', 'discussion', 'vote_announcement', 'voting', 'vote_result', 'finished')),
  round_number integer not null default 1 check (round_number between 1 and 5),
  phase_ends_at timestamptz,
  current_clue_id uuid references mafioso_case_clues(id) on delete set null,
  final_winner text check (final_winner in ('mafia', 'innocent')),
  last_eliminated_user_id uuid references users(id) on delete set null,
  last_eliminated_alignment text check (last_eliminated_alignment in ('mafia', 'innocent')),
  created_by uuid references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists mafioso_room_players (
  room_id uuid not null references mafioso_rooms(id) on delete cascade,
  user_id uuid not null references users(id) on delete cascade,
  role_id uuid references mafioso_case_roles(id) on delete set null,
  alignment text check (alignment in ('mafia', 'innocent')),
  status text not null default 'active' check (status in ('active', 'eliminated', 'left')),
  is_connected boolean not null default true,
  role_acknowledged_at timestamptz,
  joined_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table if not exists mafioso_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references mafioso_rooms(id) on delete cascade,
  round_number integer not null check (round_number between 1 and 5),
  user_id uuid references users(id) on delete set null,
  body text not null check (char_length(trim(body)) between 1 and 420),
  created_at timestamptz not null default now()
);

create table if not exists mafioso_votes (
  id bigint generated by default as identity primary key,
  room_id uuid not null references mafioso_rooms(id) on delete cascade,
  round_number integer not null check (round_number between 1 and 5),
  voter_id uuid not null references users(id) on delete cascade,
  target_id uuid not null references users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(room_id, round_number, voter_id)
);

